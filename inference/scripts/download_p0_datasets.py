def _ssl_ctx() -> ssl.SSLContext:
    ctx = ssl.create_default_context()
    ctx.check_hostname = True
    return ctx


def _opener() -> urllib.request.OpenerDirector:
    handler = urllib.request.HTTPSHandler(context=_ssl_ctx())
    return urllib.request.build_opener(handler)


def probe(url: str, timeout: int = 8) -> tuple[bool, str]:
    """探测 URL 可达性（HEAD 优先，失败回退 GET range）。"""
    op = _opener()
    req = urllib.request.Request(url, method="HEAD", headers={"User-Agent": USER_AGENT})
    try:
        with op.open(req, timeout=timeout) as resp:
            return True, f"HTTP {resp.status}"
    except Exception as e1:  # noqa: BLE001
        try:
            req2 = urllib.request.Request(
                url,
                headers={"User-Agent": USER_AGENT, "Range": "bytes=0-0"},
            )
            with op.open(req2, timeout=timeout) as resp:
                return True, f"HTTP {resp.status} (GET)"
        except Exception as e2:  # noqa: BLE001
            return False, f"{type(e1).__name__}: {e1} / {type(e2).__name__}: {e2}"


def fetch(url: str, dest: Path, timeout: int = TIMEOUT) -> Path:
    """下载 URL 到 dest，返回落盘路径。"""
    op = _opener()
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_suffix(dest.suffix + ".part")
    with op.open(req, timeout=timeout) as resp, open(tmp, "wb") as f:
        while True:
            chunk = resp.read(65536)
            if not chunk:
                break
            f.write(chunk)
    tmp.replace(dest)
    return dest


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


