def handle_dataset(name: str, ds: dict, check_only: bool = False) -> dict:
    root = DATA_ROOT / ds["dest"]
    root.mkdir(parents=True, exist_ok=True)
    status = {
        "name": name,
        "title": ds["name"],
        "priority": ds["priority"],
        "meta_downloaded": [],
        "meta_failed": [],
        "restricted_reachable": None,
        "restricted_status": "待处理",
        "artifacts": [],
    }

    # 1) 元数据自动拉取
    for rel, url in ds.get("meta_files", {}).items():
        target = root / rel
        if target.exists() and target.stat().st_size > 0:
            status["meta_downloaded"].append(f"{rel} (已存在)")
            continue
        if check_only:
            ok, msg = probe(url)
            if ok:
                status["meta_downloaded"].append(f"{rel} (可达)")
            else:
                status["meta_failed"].append(f"{rel}: {msg}")
            continue
        try:
            fetch(url, target)
            status["meta_downloaded"].append(rel)
            time.sleep(0.3)  # 对 GitHub 礼貌限速
        except Exception as e:  # noqa: BLE001
            status["meta_failed"].append(f"{rel}: {type(e).__name__}: {e}")

    # 2) 受限来源探测/指引
    restr = ds.get("restricted")
    if restr:
        ok, msg = probe(restr["url"])
        status["restricted_reachable"] = ok
        if check_only:
            status["restricted_status"] = "可达（可自动）" if ok else f"不可达: {msg}"
        elif ok:
            if restr["kind"] == "baidu_pan":
                status["restricted_status"] = (
                    "来源站点可达；但百度网盘需登录与提取码，脚本无法自动拉取，"
                    "请按指引手动下载后放入目录。"
                )
            else:
                status["restricted_status"] = (
                    f"来源站点可达（{restr['kind']}）。该平台需登录/人工，"
                    "请按指引手动下载放入对应目录。"
                )
        else:
            status["restricted_status"] = (
                f"来源当前不可达（{msg}）。请人工下载后放入目录。"
            )

    # 3) dataset.yaml 落盘（占位/生成）
    yaml_text = ds.get("dataset_yaml")
    if yaml_text and not check_only:
        yaml_path = root / "dataset.yaml"
        if not yaml_path.exists():
            yaml_path.write_text(yaml_text, encoding="utf-8")
            status["artifacts"].append(str(yaml_path))
        else:
            status["artifacts"].append(f"{yaml_path} (已存在)")

    # 4) 人工下载指引 README
    if restr and not check_only:
        readme = root / "HOW_TO_DOWNLOAD.md"
        lines = [
            f"# {ds['name']} — 下载指引",
            "",
            f"- 优先级: {ds['priority']}",
            f"- 类别: {ds['category']}",
            f"- 来源: {ds['source']}",
            f"- 引用: {ds['citation']}",
            "",
            "## 下载地址",
            f"链接: {restr['url']}",
        ]
        if restr.get("code"):
            lines += ["", f"提取码: {restr['code']}"]
        lines += ["", "## 说明", restr["note"], "", "## 期望目录结构", restr["expected_layout"], ""]
        readme.write_text("\n".join(lines), encoding="utf-8")
        status["artifacts"].append(str(readme))

    return status


def main() -> int:
    ap = argparse.ArgumentParser(description="P0 数据集下载脚本（河道生态评估）")
    ap.add_argument("names", nargs="*", help="数据集名（缺省=全部）")
    ap.add_argument("--list", action="store_true", help="列出注册表与本地状态")
    ap.add_argument("--check-only", action="store_true", help="仅探测来源可达性")
    args = ap.parse_args()

    DATA_ROOT.mkdir(parents=True, exist_ok=True)

    if args.list:
        print(f"{'名称':<8}{'P':<4}{'类别':<14}{'图像':<8}{'来源':<30}本地状态")
        for name, ds in DATASETS.items():
            root = DATA_ROOT / ds["dest"]
            n = sum(1 for p in root.rglob("*") if p.is_file()) if root.exists() else 0
            print(
                f"{name:<8}{ds['priority']:<4}{ds['category']:<14}"
                f"{sum(ds['splits'].values()):<8}{ds['source']:<30}{n} 个文件"
            )
        return 0

    names = args.names or list(DATASETS)
    unknown = [n for n in names if n not in DATASETS]
    if unknown:
        print(f"未知数据集: {unknown}；可用: {', '.join(DATASETS)}")
        return 2

    print(f"数据根目录: {DATA_ROOT}\n")
    for name in names:
        ds = DATASETS[name]
        print(f"===== {name} — {ds['name']} =====")
        print(f"  {ds['summary']}")
        st = handle_dataset(name, ds, check_only=args.check_only)
        if st["meta_downloaded"]:
            print(f"  [元数据] {'; '.join(st['meta_downloaded'])}")
        if st["meta_failed"]:
            print(f"  [元数据失败] {'; '.join(st['meta_failed'])}")
        print(f"  [受限来源] {st['restricted_status']}")
        for a in st["artifacts"]:
            print(f"  [产物] {a}")
        print()
    return 0


